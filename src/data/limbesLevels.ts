import { LEVEL_COLS, LEVEL_ROWS, type Level } from "./levels";

/** Low bits of a brick (§4). `4` stands for 0x24; 0x27 behaves the same and is not used. */
const BRICKS: Readonly<Record<string, number>> = {
  ".": 0,
  "#": 0x21,
  "4": 0x24,
  "~": 0x11,
  X: 0x08,
  T: 0x18,
};

function cell(kind: string, color: string, where: string): number {
  const low = BRICKS[kind];
  const high = Number(color);
  if (low === undefined || !(high >= 0 && high <= 3)) throw new Error(`bad brick at ${where}`);
  return low === 0 ? 0 : (high << 6) | low;
}

/** "kinds colors": 13 brick characters, then one colour for all of them or one for each. */
function parseRow(text: string, where: string): number[] {
  const [kinds = "", colors = ""] = text.split(" ");
  const each = colors.length === 1 ? colors.repeat(LEVEL_COLS) : colors;
  if (kinds.length !== LEVEL_COLS || each.length !== LEVEL_COLS) {
    throw new Error(`bad row at ${where}: ${text}`);
  }
  return [...kinds].map((kind, c) => cell(kind, each[c]!, `${where}, column ${c}`));
}

/** Rows from `first` down; the others stay empty. */
function level(first: number, ...rows: readonly string[]): Level {
  const grid = Array.from({ length: LEVEL_ROWS }, () => Array<number>(LEVEL_COLS).fill(0));
  rows.forEach((text, i) => {
    grid[first + i] = parseRow(text, `row ${first + i}`);
  });
  return grid;
}

